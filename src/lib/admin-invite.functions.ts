import { createServerFn } from "@tanstack/react-start";
import { z } from "zod";

import { requireSupabaseAuth } from "@/integrations/supabase/auth-middleware";

/**
 * Issues an admin invitation.
 *
 * Creating the auth.users row is the one step of the flow that cannot happen in
 * SQL — writing auth.users from a public definer function bypasses GoTrue's
 * password hashing and auth.identities bookkeeping — so it runs here, against
 * the service-role key.
 *
 * Three things about this file matter:
 *
 * 1. `*.functions.ts` modules ship to the client bundle, so
 *    `client.server.ts` MUST be imported dynamically inside the handler. A
 *    top-level import would leak the service-role client into the browser
 *    bundle. This is spelled out in client.server.ts's own header comment.
 *
 * 2. Authorisation is checked twice, and the important check is the second
 *    one. `is_super_admin` is called through the *user-scoped* client the
 *    middleware provides, so the answer comes from the caller's own JWT and
 *    cannot be spoofed. admin_invite_create() then re-checks it in the
 *    database. The service-role client is used only after both have passed,
 *    and only for the GoTrue call.
 *
 * 3. The one-time password is generated by the database (pgcrypto CSPRNG) and
 *    returned exactly once. It is handed to Supabase as user metadata purely so
 *    the invite email template can render `{{ .Data.dialearn_otp }}`, then
 *    scrubbed on the very next call — the plaintext lives in the user record
 *    for about a second and never reaches the browser.
 */

const INVITE_SCHEMA = z.object({
  email: z
    .string()
    .trim()
    .min(1, "Please enter a work email address.")
    .max(254, "That email address is too long.")
    .regex(/^[^@\s]+@[^@\s]+\.[^@\s]+$/, "Please enter a valid email address.")
    .transform((value) => value.toLowerCase()),
  role: z.enum(["admin", "super_admin"]),
  permissionKeys: z.array(z.string()).max(64).default([]),
  origin: z.string().url(),
});

export type InviteAdminInput = z.input<typeof INVITE_SCHEMA>;

type InviteAdminResult =
  | { ok: false; fieldErrors: Record<string, string> }
  | { ok: false; formError: string }
  | {
      ok: true;
      invitationId: string;
      emailed: boolean;
      /** Present only when the invitee already had an account, so no invite
       *  mail could be sent and the code must be shared another way. */
      otp?: string;
      expiresAt: string;
    };

/** Maps the SCREAMING_SNAKE codes the RPCs raise onto sentences. */
function friendlyRpcError(message: string): string {
  const raw = (message || "").toUpperCase();
  if (raw.includes("NOT_AUTHORIZED")) return "Only a super admin can invite admins.";
  if (raw.includes("INVITE_DOMAIN_ALLOWLIST_EMPTY"))
    return "No invite domains are configured yet. Add at least one work email domain in Platform settings first.";
  if (raw.includes("EMAIL_DOMAIN_NOT_ALLOWED"))
    return "That email domain isn't on the allowed list for admin invitations.";
  if (raw.includes("INVALID_EMAIL")) return "Please enter a valid email address.";
  if (raw.includes("INVALID_ROLE")) return "That role can't be invited.";
  if (raw.includes("UNKNOWN_PERMISSION_KEY"))
    return "One of the selected permissions no longer exists.";
  return "We couldn't create that invitation. Please try again.";
}

export const inviteAdmin = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: InviteAdminInput) => input)
  .handler(async ({ data, context }): Promise<InviteAdminResult> => {
    const parsed = INVITE_SCHEMA.safeParse(data);
    if (!parsed.success) {
      const fieldErrors: Record<string, string> = {};
      for (const issue of parsed.error.issues) {
        const key = String(issue.path[0] ?? "form");
        if (!fieldErrors[key]) fieldErrors[key] = issue.message;
      }
      return { ok: false, fieldErrors };
    }

    const { email, role, permissionKeys, origin } = parsed.data;

    // types.ts predates these functions, so the generated rpc() overload does
    // not know their names.
    const userScoped = context.supabase as unknown as {
      rpc: (
        fn: string,
        args?: Record<string, unknown>,
      ) => Promise<{ data: unknown; error: { message: string } | null }>;
    };

    const superAdminCheck = await userScoped.rpc("is_super_admin");
    if (superAdminCheck.error || superAdminCheck.data !== true) {
      return { ok: false, formError: "Only a super admin can invite admins." };
    }

    const created = await userScoped.rpc("admin_invite_create", {
      p_email: email,
      p_role: role,
      p_permission_keys: permissionKeys,
    });
    if (created.error) {
      return { ok: false, formError: friendlyRpcError(created.error.message) };
    }

    const row = (
      created.data as { invitation_id: string; otp: string; expires_at: string }[] | null
    )?.[0];
    if (!row) {
      return { ok: false, formError: "We couldn't create that invitation. Please try again." };
    }

    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");

    const invited = await supabaseAdmin.auth.admin.inviteUserByEmail(email, {
      data: { dialearn_otp: row.otp },
      redirectTo: `${origin}/auth/accept-invite`,
    });

    if (invited.error) {
      const alreadyRegistered = /already|registered|exists/i.test(invited.error.message);
      if (alreadyRegistered) {
        // GoTrue will not re-invite an existing account, so no mail goes out.
        // The invitation itself is valid — surface the code once so the super
        // admin can pass it on, and tell them to send the person to
        // /auth/accept-invite.
        return {
          ok: true,
          invitationId: row.invitation_id,
          emailed: false,
          otp: row.otp,
          expiresAt: row.expires_at,
        };
      }
      return { ok: false, formError: "We couldn't send that invitation email. Please try again." };
    }

    // Scrub the plaintext code now the template has rendered it.
    const newUserId = invited.data.user?.id;
    if (newUserId) {
      await supabaseAdmin.auth.admin.updateUserById(newUserId, {
        user_metadata: { dialearn_otp: null },
      });
    }

    return {
      ok: true,
      invitationId: row.invitation_id,
      emailed: true,
      expiresAt: row.expires_at,
    };
  });
